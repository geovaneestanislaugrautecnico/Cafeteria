insert into public.pagamentos (pedido_id,metodo,valor,status,pago_em)
select p.id,
  case when p.id % 3 = 0 then 'pix' when p.id % 3 = 1 then 'cartao' else 'dinheiro' end,
  coalesce((select sum(i.quantidade*i.preco_unitario) from public.itens_pedido i where i.pedido_id=p.id),0),
  case when p.status='cancelado' then 'estornado' when p.id % 4 = 0 then 'pendente' else 'aprovado' end,
  case when p.status='cancelado' then null else now() - interval '1 day' end
from public.pedidos p;

