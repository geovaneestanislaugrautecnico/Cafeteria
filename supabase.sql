create table public.clientes (
  id bigint generated by default as identity primary key,
  nome varchar(100) not null,
  cpf varchar(11) unique,
  email varchar(255) unique,
  telefone varchar(20),
  criado_em timestamptz not null default now()
);

create table public.categorias (
  id bigint generated by default as identity primary key,
  nome varchar(80) not null unique,
  descricao text,
  ativo boolean not null default true
);

create table public.produtos (
  id bigint generated by default as identity primary key,
  categoria_id bigint references public.categorias(id) on delete set null,
  nome varchar(120) not null,
  descricao text,
  preco numeric(10,2) not null check (preco >= 0),
  disponivel boolean not null default true,
  criado_em timestamptz not null default now()
);

create table public.pedidos (
  id bigint generated by default as identity primary key,
  cliente_id bigint references public.clientes(id) on delete set null,
  status varchar(20) not null default 'pendente'
    check (status in ('pendente','em_preparo','pronto','entregue','cancelado')),
  observacoes text,
  criado_em timestamptz not null default now()
);

create table public.itens_pedido (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null references public.pedidos(id) on delete cascade,
  produto_id bigint references public.produtos(id) on delete set null,
  nome_produto varchar(120) not null,
  quantidade integer not null check (quantidade > 0),
  preco_unitario numeric(10,2) not null check (preco_unitario >= 0)
);

create table public.pagamentos (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null unique references public.pedidos(id) on delete cascade,
  metodo varchar(20) not null check (metodo in ('pix','cartao','dinheiro')),
  valor numeric(10,2) not null check (valor >= 0),
  status varchar(20) not null default 'pendente'
    check (status in ('pendente','aprovado','recusado','estornado')),
  pago_em timestamptz
);

create index idx_produtos_categoria on public.produtos(categoria_id);
create index idx_pedidos_cliente on public.pedidos(cliente_id);
create index idx_itens_pedido on public.itens_pedido(pedido_id);
create index idx_pagamentos_pedido on public.pagamentos(pedido_id);


